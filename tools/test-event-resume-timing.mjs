import assert from "node:assert/strict";
import { createEventRuntime } from "../src/adventure/eventRuntime.js";
import { eventDefinitions } from "../src/data/events/index.js";
import { createAdventureRuntimeState } from "../src/app/runtimeState.js";
import { buildHeroFromProgression } from "../src/core/progression.js";
import { captureRunSnapshot, restoreRunSnapshot } from "../src/core/runSnapshot.js";
import { characterDefinitions } from "../src/data/characters/index.js";
import { regionDefinitions } from "../src/data/regions/index.js";
import { TestNode, installTestDocument } from "./dom-test-stub.mjs";
installTestDocument();
const timers = [];
globalThis.window = { setTimeout(callback) { timers.push(callback); } };
const state = createAdventureRuntimeState({ characterDefinitions, regionDefinitions });
state.hero = buildHeroFromProgression(characterDefinitions.adventurer, { level: 1, exp: 0, learnedSkills: [] });
state.runStats = { levelUps: [], learnedSkills: [], unlockedCharacters: [] };
state.runRandomState = 51;
const event = Object.values(eventDefinitions)[0];
state.eventSchedule = { eventId: event.id };
const els = new Proxy({}, { get(target, key) { return target[key] ||= new TestNode(); } });
const dependencies = { state, els, currentRegion: () => regionDefinitions.forest, getAdventureSourceName: () => "森林" };
const runtime = createEventRuntime(new Proxy(dependencies, { get: (target, key) => {
  if (key in target) return target[key];
  if (key === "runSaveOperation" || key === "afterAdventureSaved") return action => action();
  return () => {};
} }));
const oldTransition = runtime.beginScheduledEvent();
const snapshot = captureRunSnapshot(state);
const oldToken = state.eventTransitionToken;
runtime.resetEventRunState();
restoreRunSnapshot(state, snapshot);
assert.notEqual(state.eventTransitionToken, oldToken);
els.eventTitle.textContent = "恢復後已完成的事件結果";
state.eventInputLocked = true;
timers.shift()();
await oldTransition;
assert.equal(els.eventTitle.textContent, "恢復後已完成的事件結果");
assert.equal(state.eventInputLocked, true, "An obsolete transition cannot unlock choices over a restored result");
assert.equal(timers.length, 0, "Obsolete animation stops at its first cancellation check");
console.log("Event resume timing: obsolete pre-resume animation cannot overwrite or unlock the restored event.");
